test('실제 도서 표본의 가이드 전략 정확도가 90% 이상이다', () => {
  const results = SAMPLE.map(book => ({ ...book, actual: selectInteractionStrategy(book) }));
  const misses = results.filter(item => item.actual !== item.expected);
  const accuracy = (results.length - misses.length) / results.length;
  assert.ok(accuracy >= 0.9, 'accuracy=' + (accuracy * 100).toFixed(1) + '% misses=' + JSON.stringify(misses));
});
